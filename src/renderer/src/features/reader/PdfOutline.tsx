import { useMemo } from 'react'
import type { PdfOutlineItem } from './pdf-outline'

export interface PdfOutlineProps {
  items: readonly PdfOutlineItem[]
  loading: boolean
  autoGenerated?: boolean
  currentPage: number
  activeItemId?: string | null
  onNavigate: (item: PdfOutlineItem) => void
  onClose: () => void
}

interface OutlineListProps {
  items: readonly PdfOutlineItem[]
  highlightedId: string | null
  nested: boolean
  onNavigate: (item: PdfOutlineItem) => void
}

function findItemById(items: readonly PdfOutlineItem[], id: string): PdfOutlineItem | null {
  for (const item of items) {
    if (item.id === id) return item
    const child = findItemById(item.items, id)
    if (child) return child
  }
  return null
}

function findFirstItemForPage(items: readonly PdfOutlineItem[], pageNumber: number): string | null {
  for (const item of items) {
    if (item.pageNumber === pageNumber) return item.id
    const childId = findFirstItemForPage(item.items, pageNumber)
    if (childId) return childId
  }
  return null
}

function OutlineList({ items, highlightedId, nested, onNavigate }: OutlineListProps): React.JSX.Element {
  return (
    <ul className={nested ? 'reader-outline__list reader-outline__list--nested' : 'reader-outline__list'}>
      {items.map(item => {
        const isActive = item.id === highlightedId
        return (
          <li key={item.id} className="reader-outline__node">
            {item.pageNumber !== null ? (
              <button
                type="button"
                className={isActive ? 'reader-outline__item is-active' : 'reader-outline__item'}
                aria-current={isActive ? 'location' : undefined}
                title={item.title}
                onClick={() => onNavigate(item)}
              >
                <span className="reader-outline__title">{item.title}</span>
                <span className="reader-outline__page">{item.pageNumber}</span>
              </button>
            ) : (
              <div className="reader-outline__group" title={item.title}>{item.title}</div>
            )}
            {item.items.length > 0 && (
              <OutlineList items={item.items} highlightedId={highlightedId} nested={true} onNavigate={onNavigate} />
            )}
          </li>
        )
      })}
    </ul>
  )
}

export function PdfOutline({
  items,
  loading,
  autoGenerated = false,
  currentPage,
  activeItemId = null,
  onNavigate,
  onClose
}: PdfOutlineProps): React.JSX.Element {
  const highlightedId = useMemo(() => {
    if (activeItemId) {
      const explicit = findItemById(items, activeItemId)
      if (explicit && explicit.pageNumber === currentPage) {
        return explicit.id
      }
    }
    return findFirstItemForPage(items, currentPage)
  }, [items, activeItemId, currentPage])

  return (
    <aside className="reader-outline" aria-label="文档目录">
      <div className="reader-outline__header">
        <div className="reader-outline__heading">
          <strong>目录</strong>
          {autoGenerated && items.length > 0 ? (
            <span className="reader-outline__badge" title="原 PDF 未内嵌书签，已根据章节标题自动生成">
              自动识别
            </span>
          ) : null}
        </div>
        <button type="button" className="reader-outline__close" aria-label="关闭目录" title="关闭目录" onClick={onClose}>×</button>
      </div>
      <div className="reader-outline__content">
        {loading ? (
          <p className="reader-outline__status" role="status">正在读取目录…</p>
        ) : items.length === 0 ? (
          <p className="reader-outline__empty" role="status">此 PDF 未包含目录书签</p>
        ) : (
          <OutlineList items={items} highlightedId={highlightedId} nested={false} onNavigate={onNavigate} />
        )}
      </div>
    </aside>
  )
}
